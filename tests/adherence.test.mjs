import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {previewProofBucket} from '../scripts/preview-proofs.mjs';
import worker from '../dist/server/index.js';

test('score uses date- and account-specific photos, allows partial credit and invalidates replaced evidence',async t=>{
  const root=await mkdtemp(join(tmpdir(),'meal-proof-'));
  t.after(()=>rm(root,{recursive:true,force:true}));
  const env={BUCKET:previewProofBucket(root),GEMINI_API_KEY:'test',GEMINI_MODEL:'gemini-test'};
  const api=(path,method='GET',body,user='u')=>worker.fetch(new Request('https://test.local/api/nutrition/adherence'+path,{method,body,headers:user?{'oai-authenticated-user-id':user}:{}}),env);
  const day='?date=2026-11-23', breakfast='/photo'+day+'&meal=breakfast';
  assert.equal((await api(day,'GET',undefined,'')).status,401);
  assert.equal((await api(breakfast,'POST','test')).status,400);
  assert.equal((await (await api(day,'POST')).json()).report.score,0);
  const bytes=new Uint8Array([255,216,255,217]);
  assert.equal((await api(breakfast,'POST',bytes)).status,200);
  assert.equal((await (await api(day)).json()).report,null);
  assert.equal((await api(breakfast,'GET',undefined,'other')).status,404);
  assert.deepEqual((await (await api('?date=2026-11-22')).json()).photos,{});
  const original=globalThis.fetch;
  t.after(()=>{globalThis.fetch=original;});
  globalThis.fetch=async()=>new Response('{}',{status:503});
  assert.equal((await api(day,'POST')).status,502);
  assert.equal((await (await api(day)).json()).report,null);
  let calls=0;
  globalThis.fetch=async()=>{calls++;return Response.json({candidates:[{content:{parts:[{text:JSON.stringify({matches:{eggs:'partial',avocado:'visible'},observation:'Avocado and two eggs.'})}]}}]});};
  const {report}=await (await api(day,'POST')).json();
  assert.equal(report.score,13);
  assert.equal(report.rows[0].fraction,0.75);
  assert.equal(report.rows.filter(r=>r.missing).length,5);
  assert.deepEqual((await (await api(day)).json()).report,report);
  await api(day,'POST');assert.equal(calls,1);
  await api(breakfast,'POST',new Uint8Array([...bytes,0]));
  assert.equal((await (await api(day)).json()).report,null);
  await api(breakfast,'DELETE');
  assert.equal((await api(breakfast)).status,404);
});
